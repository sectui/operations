import { writeFile } from "node:fs/promises";
import { kebab } from "../src/args.ts";
import { cliExample, cliFlag } from "../src/cli-flags.ts";
import type { ArgDef, Operation } from "../src/operation.ts";
import { operations } from "../src/registry.ts";

const OUTPUT = `${import.meta.dirname}/../docs/operations.md`;

function argLine(key: string, def: ArgDef): string {
  const parts = [`- \`${key}\` (CLI: \`${cliFlag(key, def)}\`, template: \`${kebab(key)}\`): ${def.name}.`];
  if (def.description) parts.push(def.description);
  if (def.type === "select") {
    parts.push(`One of ${def.options.map((o) => `\`${o.value}\` (${o.label})`).join(", ")}.`);
  } else if (def.type === "number") {
    const range = [def.min !== undefined && `min ${def.min}`, def.max !== undefined && `max ${def.max}`].filter(Boolean);
    parts.push(`Number${range.length ? ` (${range.join(", ")})` : ""}.`);
  }
  parts.push(`Default: \`${def.default}\`.`);
  return parts.join(" ");
}

function section(op: Operation): string {
  const lines = [`### \`${op.id}\``, "", `**${op.name}**: ${op.description}`, ""];
  if (op.aliases?.length) lines.push(`- Aliases: ${op.aliases.join(", ")}`);
  if (op.inverse) lines.push(`- Inverse: [\`${op.inverse}\`](#${op.inverse})`);
  if (op.infoUrl) lines.push(`- More info: <${op.infoUrl}>`);
  lines.push(`- Output: ${op.output === "binary" ? "binary (may contain arbitrary bytes)" : "text"}`);
  const args = Object.entries(op.args);
  lines.push("", args.length ? "Arguments:" : "No arguments.");
  if (args.length) lines.push("", ...args.map(([key, def]) => argLine(key, def)));
  lines.push("", "Examples:", "", "```sh", ...op.examples.map((ex) => `${cliExample(op, ex)}  # -> ${JSON.stringify(ex.output)}`), "```");
  return lines.join("\n");
}

const byCategory = Map.groupBy(operations as readonly Operation[], (op) => op.category);

const doc = [
  "<!-- Generated by scripts/gen-docs.ts from src/registry.ts. Do not edit: run `npm run docs`. -->",
  "",
  "# Operations",
  "",
  `${operations.length} operations available.`,
  "",
  ...[...byCategory].flatMap(([category, ops]) => [`- ${category}: ${ops.map((op) => `[\`${op.id}\`](#${op.id})`).join(", ")}`]),
  ...[...byCategory].flatMap(([category, ops]) => ["", `## ${category}`, "", ops.map(section).join("\n\n")]),
  "",
].join("\n");

await writeFile(OUTPUT, doc);
